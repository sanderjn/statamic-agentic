<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Statamic\Facades\Blueprint;
use Statamic\Facades\Fieldset;
use Statamic\Fields\Fields;

class BuildAgentCatalog extends Command
{
    protected $signature = 'content:catalog';

    protected $description = 'Generate the agent content catalog from selected blueprints or the page-builder fieldset.';

    public function handle(): int
    {
        $blueprints = config('agentic.catalog_blueprints', []);
        $lines = $blueprints === [] ? $this->pageBuilderLines() : $this->blueprintLines($blueprints);

        if ($lines === null) {
            return self::FAILURE;
        }

        $out = config('agentic.catalog_path');
        File::put(base_path($out), implode("\n", $lines)."\n");
        $this->info("Wrote {$out}");

        return self::SUCCESS;
    }

    private function pageBuilderLines(): ?array
    {
        $handle = config('agentic.page_builder_fieldset');
        $fieldHandle = config('agentic.page_builder_field') ?? $handle;

        if (! $fieldset = Fieldset::find($handle)) {
            $this->error("{$handle} fieldset not found.");

            return null;
        }

        if (! $field = $fieldset->fields()->all()->get($fieldHandle)) {
            $this->error("{$fieldHandle} field not found in {$handle} fieldset.");

            return null;
        }

        $lines = [
            '# Page-builder section reference',
            '',
            '_Generated by `php artisan content:catalog`. Do not hand-edit._',
            '',
            'These are the only page-builder sections you may use, with their fields. Use exactly',
            'these handles, and for choice fields use exactly one of the options listed.',
            '',
        ];

        foreach ($this->flattenSets($field->get('sets', [])) as $handle => $set) {
            $lines[] = '## '.($set['display'] ?? $handle)." (`{$handle}`)";
            if (! empty($set['instructions'])) {
                $lines[] = '';
                $lines[] = $set['instructions'];
            }
            $lines[] = '';

            $lines = array_merge($lines, $this->fieldLines(new Fields($set['fields'] ?? []), 0));

            $lines[] = '';
        }

        return $lines;
    }

    private function blueprintLines(array $handles): ?array
    {
        $lines = [
            '# Content blueprint reference',
            '',
            '_Generated by `php artisan content:catalog`. Do not hand-edit._',
            '',
            'These are the selected blueprints and their fields. Follow the site brief for editing',
            'permissions, content locations, page creation, and publishing; this reference does not grant access.',
            'Use option keys, not labels. Relationship targets below are handles, not record IDs.',
            'Field types describe the schema, not every storage format or custom behavior.',
            'If a field or content structure is unfamiliar, ask the developer rather than guessing.',
            '',
        ];

        foreach ($handles as $handle) {
            if (! $blueprint = Blueprint::find($handle)) {
                $this->error("{$handle} blueprint not found. The existing catalog was not changed.");

                return null;
            }

            $lines[] = '## '.$blueprint->title()." (`{$handle}`)";
            $lines[] = '';
            $lines = array_merge($lines, $this->fieldLines($blueprint->fields(), 0));
            $lines[] = '';
        }

        return $lines;
    }

    /**
     * One markdown bullet per field, recursing into replicator/Bard sets and
     * group/grid children so nested building blocks are catalogued too.
     */
    private function fieldLines(Fields $fields, int $depth): array
    {
        $lines = [];
        $pad = str_repeat('    ', $depth);

        foreach ($fields->all() as $handle => $field) {
            $line = "{$pad}- `{$handle}` — ".$field->type().($field->isRequired() ? ' (required)' : '');

            $options = $field->get('options', []);
            if (! empty($options)) {
                $keys = array_is_list($options)
                    ? array_map(fn ($option) => is_array($option) ? $option['key'] : $option, $options)
                    : array_keys($options);
                $line .= '; options: '.implode(', ', $keys);
            }

            foreach (['collections', 'taxonomies', 'container'] as $target) {
                if ($value = $field->get($target)) {
                    $line .= "; {$target}: ".implode(', ', (array) $value);
                }
            }

            $lines[] = $line;

            if ($instructions = $field->get('instructions')) {
                foreach (explode("\n", $instructions) as $instruction) {
                    $lines[] = "{$pad}    {$instruction}";
                }
            }

            if (in_array($field->type(), ['replicator', 'bard'], true)) {
                foreach ($this->flattenSets($field->get('sets', [])) as $subHandle => $subSet) {
                    $display = $subSet['display'] ?? null;
                    $lines[] = "{$pad}    - items of type `{$subHandle}`".($display ? " ({$display})" : '').', with:';
                    if ($instructions = $subSet['instructions'] ?? null) {
                        foreach (explode("\n", $instructions) as $instruction) {
                            $lines[] = "{$pad}        {$instruction}";
                        }
                    }
                    $lines = array_merge($lines, $this->fieldLines(new Fields($subSet['fields'] ?? []), $depth + 2));
                }
            } elseif (in_array($field->type(), ['group', 'grid'], true)) {
                $lines = array_merge($lines, $this->fieldLines(new Fields($field->get('fields', [])), $depth + 1));
            }
        }

        return $lines;
    }

    /**
     * Flatten a replicator's grouped `sets` config to [setHandle => setConfig].
     *
     * @param  array<string, mixed>  $sets
     * @return array<string, array<string, mixed>>
     */
    private function flattenSets(array $sets): array
    {
        $flat = [];

        foreach ($sets as $handle => $config) {
            if (isset($config['sets']) && is_array($config['sets'])) {
                foreach ($config['sets'] as $setHandle => $setConfig) {
                    $flat[$setHandle] = $setConfig;
                }
            } else {
                $flat[$handle] = $config;
            }
        }

        return $flat;
    }
}
